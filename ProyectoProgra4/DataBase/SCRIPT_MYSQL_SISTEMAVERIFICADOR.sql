
   DROP DATABASE IF EXISTS SistemaVerificador;
   CREATE DATABASE SistemaVerificador;

USE SistemaVerificador;


CREATE TABLE CLIENTE (
    ID_CLIENTE VARCHAR(20) NOT NULL PRIMARY KEY,
    SIG_PAIS CHAR(2) NOT NULL,
    NOMBRE VARCHAR(20) NOT NULL,
    PRIM_APELLIDO VARCHAR(20) NOT NULL,
    SEG_APELLIDO VARCHAR(20) NOT NULL,
    CORREO VARCHAR(100) NOT NULL,
    TELEFONO VARCHAR(18) NOT NULL,
    DIRECCION VARCHAR(150) NOT NULL

);

CREATE TABLE COMPRA(
ID_COMPRA VARCHAR(10) NOT NULL PRIMARY KEY, 
ID_CLIENTE VARCHAR(20) NOT NULL,
FECHA_COMPRA DATE NOT NULL, 
TOTAL_COMPRA DECIMAL(10,2) NOT NULL,
NUM_TARJETA VARCHAR(255) NOT NULL, 
FECHA_VENCIMIENTO VARCHAR(255) NOT NULL,
CODIGO_VERIFICACION VARCHAR(255) NOT NULL, 
CONSTRAINT CK_TOTAL_COMPRA CHECK(TOTAL_COMPRA > 0),


CONSTRAINT FK_COMPRAS_CLIENTE
FOREIGN KEY (ID_CLIENTE)
REFERENCES CLIENTE(ID_CLIENTE)


);

CREATE TABLE DETALLE_COMPRA (
ID_DETALLE INT AUTO_INCREMENT PRIMARY KEY, 
ID_COMPRA VARCHAR(10) NOT NULL,
ID_PRODUCTO VARCHAR(10) NOT NULL, 
CANTIDAD INT NOT NULL,

CONSTRAINT CK_CANTIDAD CHECK(CANTIDAD > 0),
CONSTRAINT FK_DETALLE_COMPRA 
FOREIGN KEY (ID_COMPRA)
REFERENCES COMPRA(ID_COMPRA)
);


DELIMITER //

CREATE PROCEDURE SP_INSERTAR_CLIENTE (
    IN P_ID_CLIENTE VARCHAR(20),
    IN P_SIG_PAIS CHAR(2),
    IN P_NOMBRE VARCHAR(20),
    IN P_PRIM_APELLIDO VARCHAR(20),
    IN P_SEG_APELLIDO VARCHAR(20),
    IN P_CORREO VARCHAR(100),
    IN P_TELEFONO VARCHAR(18),
    IN P_DIRECCION VARCHAR(150)
)
BEGIN
    INSERT INTO CLIENTE (
        ID_CLIENTE, SIG_PAIS, NOMBRE, PRIM_APELLIDO,
        SEG_APELLIDO, CORREO, TELEFONO, DIRECCION
    )
    VALUES (
        P_ID_CLIENTE, P_SIG_PAIS, P_NOMBRE, P_PRIM_APELLIDO,
        P_SEG_APELLIDO, P_CORREO, P_TELEFONO, P_DIRECCION
    );
END //

DELIMITER ;

DELIMITER //

CREATE PROCEDURE SP_MODIFICAR_CLIENTE (
    IN P_ID_CLIENTE VARCHAR(20),
    IN P_SIG_PAIS CHAR(2),
    IN P_NOMBRE VARCHAR(20),
    IN P_PRIM_APELLIDO VARCHAR(20),
    IN P_SEG_APELLIDO VARCHAR(20),
    IN P_CORREO VARCHAR(100),
    IN P_TELEFONO VARCHAR(18),
    IN P_DIRECCION VARCHAR(150)
)
BEGIN
UPDATE CLIENTE 
SET SIG_PAIS = P_SIG_PAIS,
	NOMBRE = P_NOMBRE,
	PRIM_APELLIDO = P_PRIM_APELLIDO,
	SEG_APELLIDO = P_SEG_APELLIDO,
	CORREO = P_CORREO,
	TELEFONO = P_TELEFONO,
	DIRECCION = P_DIRECCION
WHERE ID_CLIENTE = P_ID_CLIENTE;
END //

DELIMITER ;

DELIMITER // 
CREATE PROCEDURE SP_BORRAR_CLIENTE(
IN P_ID_CLIENTE varchar(20)
)
BEGIN
DELETE FROM CLIENTE
WHERE ID_CLIENTE =  P_ID_CLIENTE;

END // 
DELIMITER ; 

DELIMITER // 
CREATE PROCEDURE SP_EXISTE_CLIENTE(
IN P_ID_CLIENTE VARCHAR(20)
)
BEGIN 
IF EXISTS(SELECT 1 FROM CLIENTE WHERE ID_CLIENTE = P_ID_CLIENTE)
THEN SELECT 1 AS EXISTE;
ELSE 
SELECT 0 AS EXISTE;
END IF;
END // 
DELIMITER ;  
DELIMITER // 

CREATE PROCEDURE SP_CLIENTE_TIENE_COMPRAS(
IN P_ID_CLIENTE VARCHAR(20)
)
BEGIN 
SELECT COUNT(*) AS CANTIDAD_COMPRAS
FROM COMPRA
WHERE ID_CLIENTE = P_ID_CLIENTE ; 
END // 
DELIMITER ;  

DELIMITER // 
CREATE PROCEDURE SP_EXISTE_COMPRA(
IN P_ID_COMPRA VARCHAR(10)
)
BEGIN 
IF EXISTS(SELECT 1 FROM COMPRA WHERE ID_COMPRA = P_ID_COMPRA ) 
THEN SELECT 1 AS EXISTE; 
ELSE 
SELECT 0 AS EXISTE;
END IF;
END // 
DELIMITER ; 

DELIMITER // 
CREATE PROCEDURE SP_INSERTAR_COMPRA(
IN P_ID_COMPRA VARCHAR(10) , 
IN P_ID_CLIENTE VARCHAR(20) ,
IN P_FECHA_COMPRA DATE , 
IN P_TOTAL_COMPRA DECIMAL(10,2) ,
IN P_NUM_TARJETA VARCHAR(255) , 
IN P_FECHA_VENCIMIENTO VARCHAR(255) ,
IN P_CODIGO_VERIFICACION VARCHAR(255)
)
BEGIN 
INSERT INTO COMPRA(
ID_COMPRA , ID_CLIENTE  ,FECHA_COMPRA , TOTAL_COMPRA  ,
NUM_TARJETA  , FECHA_VENCIMIENTO  ,CODIGO_VERIFICACION 
)
VALUES (
P_ID_COMPRA, P_ID_CLIENTE,P_FECHA_COMPRA, P_TOTAL_COMPRA,
P_NUM_TARJETA, P_FECHA_VENCIMIENTO,P_CODIGO_VERIFICACION
);

END // 
DELIMITER ; 

DELIMITER // 
CREATE PROCEDURE SP_INSERTAR_DETALLE_COMPRA(
IN P_ID_COMPRA VARCHAR(10),
IN P_ID_PRODUCTO VARCHAR(10),
IN P_CANTIDAD INT 
)
BEGIN 
INSERT INTO DETALLE_COMPRA (
ID_COMPRA , ID_PRODUCTO, CANTIDAD 
)
VALUES(
P_ID_COMPRA , P_ID_PRODUCTO, P_CANTIDAD 
);

END//
